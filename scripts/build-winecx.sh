#!/bin/bash
# Configure, build and install our x86_64 CrossOver-lineage Wine (Wine 10.0 +
# CodeWeavers patches from crossover-sources-25.1.0) into runtimes/winecx.
# Run scripts/build-winecx-deps.sh first (gmp/nettle/gnutls/freetype).
#
#   scripts/build-winecx.sh            configure (if needed) + make + install
#   scripts/build-winecx.sh configure  re-run configure only
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/upstream/crossover-sources-25.1.0/sources/wine"
# WINECX_PREFIX / WINECX_BUILD build a second copy next to the live one (e.g.
# runtimes/winecx-sse + build/x86_64-sse), so a running bottle is never touched.
# The prefix must already hold the deps: clone the live runtime with `cp -Rc` first.
PREFIX="${WINECX_PREFIX:-$ROOT/runtimes/winecx}"
BUILD="${WINECX_BUILD:-$ROOT/build/x86_64}/wine"
SDK="$(xcrun --show-sdk-path)"
JOBS="$(sysctl -n hw.ncpu)"
mkdir -p "$BUILD"; cd "$BUILD"

# Native arm64 clang emitting x86_64 code; the produced tools (widl, wrc,
# winebuild, makedep ...) are x86_64 and run under Rosetta during the build.
export CC="/usr/bin/clang -arch x86_64"
export CXX="/usr/bin/clang++ -arch x86_64"
export CPPFLAGS="-I$PREFIX/include"
export LDFLAGS="-L$PREFIX/lib"
export PKG_CONFIG="/opt/homebrew/bin/pkg-config"
export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$SDK/usr/lib/pkgconfig"
export PATH="/opt/homebrew/opt/bison/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin"
export BISON=/opt/homebrew/opt/bison/bin/bison
export FLEX=/usr/bin/flex

CONFIGURE_FLAGS=(
  --host=x86_64-apple-darwin
  --prefix="$PREFIX"
  --enable-win64                 # 64-bit unix side (x86_64, runs under Rosetta)
  --enable-archs=i386,x86_64     # new-style WoW64: i386 + x86_64 PE DLLs, one 64-bit unix side
  --disable-tests
  --without-x                    # winemac.drv only, like CrossOver
  --without-gstreamer            # not built for x86_64 yet (see NOTES.md)
  --without-sdl                  # idem; winebus uses IOHID on macOS anyway
  --without-vulkan               # no x86_64 MoltenVK yet; D3DMetal does not need it
  --with-freetype --with-gnutls
  # PE side: Homebrew mingw-w64 (arm64 host cross compilers)
  i386_CC=/opt/homebrew/bin/i686-w64-mingw32-gcc
  x86_64_CC=/opt/homebrew/bin/x86_64-w64-mingw32-gcc
  # i386 float math in SSE, not x87: mingw gcc defaults to x87 for i686, which Rosetta 2
  # emulates slowly (32-bit DirectSound mixer at ~98% of a core, docs/portal2-audio.md).
  # CrossOver's i386 DLLs are SSE too. x86_64 is SSE by ABI, so x86_64_CFLAGS stays default.
  i386_CFLAGS="-g -O2 -msse2 -mfpmath=sse"
)

# CodeWeavers generate this header in their packaging; the crash dialog's
# resources need it. Same two macros Gcenx's wine-crossover builds define.
DISTVERSION="$SRC/programs/winedbg/distversion.h"
[ -f "$DISTVERSION" ] || cat > "$DISTVERSION" <<'EOH'
/* distversion.h - generated by scripts/build-winecx.sh (not part of the tarball) */
#define WINDEBUG_WHAT_HAPPENED_MESSAGE "This can be caused by a problem in the program or a deficiency in Wine. You may want to check <a href=\"https://appdb.winehq.org\">the Application Database</a> for tips about running this application."
#define WINDEBUG_USER_SUGGESTION_MESSAGE "If this problem is not present under Windows and has not been reported yet, you can save the detailed information to a file using the \"Save As\" button, then <a href=\"https://wiki.winehq.org/Bugs\">file a bug report</a> and attach that file to the report."
EOH

# Our own fixes on top of CodeWeavers' tree: src/patches/*.patch (e.g. winemac-qt5-opengl.patch,
# docs/worms-opengl.md). The .diff there is only the CrossOver-vs-Wine-10.0 reference, never applied.
# Idempotent: a patch that already reverses cleanly is in the tree and is skipped.
for p in "$ROOT"/src/patches/*.patch; do
  [ -e "$p" ] || continue
  patch -p1 -R --dry-run -s -f -d "$SRC" < "$p" > /dev/null 2>&1 && continue
  echo "=== applying $(basename "$p")"
  patch -p1 -s -f -d "$SRC" < "$p"
done

if [ "${1:-}" = configure ] || [ ! -f Makefile ]; then
  echo "=== $(date '+%H:%M:%S') configure"
  "$SRC/configure" "${CONFIGURE_FLAGS[@]}" 2>&1 | tee configure.out | tail -40
fi
[ "${1:-}" = configure ] && exit 0

echo "=== $(date '+%H:%M:%S') make -j$JOBS"
SECONDS=0
make -j"$JOBS" > make.log 2>&1 || { tail -40 make.log; exit 1; }
echo "=== build took $((SECONDS/60)) min $((SECONDS%60)) s"
echo "=== $(date '+%H:%M:%S') make install"
make install > install.log 2>&1
# CrossOver's ntdll hardcodes the loader name "wineloader" (dlls/ntdll/unix/loader.c,
# "CrossOver hacks it to be wineloader"); their install-image rule renames bin/wine.
# We keep bin/wine and add the name ntdll expects, otherwise no child process
# (wineboot, start.exe, ...) can be spawned: "run_wineboot failed to start wineboot 1".
ln -sf wine "$PREFIX/bin/wineloader"
# ntdll always searches its own lib/wine dir BEFORE every WINEDLLPATH entry
# (dlls/ntdll/unix/loader.c set_dll_path: dll_paths[0] = dll_dir), so putting
# runtimes/d3dmetal first in WINEDLLPATH is NOT enough: Wine's own d3d11/d3d12/
# dxgi would always win. Move the DLLs that D3DMetal replaces to a side dir;
# scripts/winecx-env.sh picks d3dmetal or wined3d by putting one of the two
# dirs into WINEDLLPATH.
# Both PE arches and d3d9 too (2026-10-22, docs/dxmt-dxvk.md "Runtime layout"): DXVK
# (d3d9/d3d10core/d3d11/dxgi, i386 + x86_64) and DXMT (d3d10core/d3d11/dxgi, i386 + x86_64)
# are selected the same way, so Wine's copies of everything they replace must not sit in
# lib/wine. Every backend then uses WINEDLLPATH=<backend>:lib/wined3d:lib/wine, with
# lib/wined3d as the fallback for what the backend lacks (D3DMetal: all of i386 and d3d9).
for arch in x86_64-windows i386-windows; do
  mkdir -p "$PREFIX/lib/wined3d/$arch"
  for d in d3d9 d3d10 d3d10_1 d3d10core d3d11 d3d12 dxgi; do
    [ -f "$PREFIX/lib/wine/$arch/$d.dll" ] && mv -f "$PREFIX/lib/wine/$arch/$d.dll" "$PREFIX/lib/wined3d/$arch/"
  done
done
echo "=== $(date '+%H:%M:%S') done -> $PREFIX"
ls "$PREFIX/lib/wine"
